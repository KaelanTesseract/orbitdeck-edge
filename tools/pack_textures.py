"""Packs the scene textures as data URLs into widget/scripts/textures.js (iCUE may refuse file:// images in WebGL).
Usage: python -I tools/pack_textures.py <src-dir> <out.js>"""
import base64, io, sys
from PIL import Image

src, dst = sys.argv[1].rstrip('/') + '/', sys.argv[2]
jobs = [('saturn', 'planet_amber.jpg', (2048, 1024), 88), ('ring', '2k_saturn_ring_alpha.png', None, None),
        ('moon', '2k_moon.jpg', (1024, 512), 82), ('mercury', '2k_mercury.jpg', (1024, 512), 82),
        ('ceres', '2k_ceres_fictional.jpg', (1024, 512), 82), ('sky', '2k_stars_milky_way.jpg', (2048, 1024), 82),
        ('jupiter', '2k_jupiter.jpg', (2048, 1024), 85), ('neptune', '2k_neptune.jpg', (2048, 1024), 85),
        ('mars', '2k_mars.jpg', (2048, 1024), 84)]
out = ['// Scene textures as data URLs (WebGL may refuse file:// images in iCUE). Generated by tools/pack_textures.py.',
       '// Source: Solar System Scope (https://www.solarsystemscope.com/textures/), CC BY 4.0, based on NASA imagery.',
       '// Changes: resized, recompressed; the planet map is contrast-boosted and recoloured (tools/bake_planet.py).',
       'window.ORBIT_TEXTURES = {']
for key, f, size, q in jobs:
    im = Image.open(src + f); buf = io.BytesIO()
    if q is None: im.save(buf, 'PNG', optimize=True); mime = 'image/png'
    else: im.convert('RGB').resize(size, Image.LANCZOS).save(buf, 'JPEG', quality=q, optimize=True); mime = 'image/jpeg'
    out.append(f"  {key}: 'data:{mime};base64,{base64.b64encode(buf.getvalue()).decode()}',")
    print(key, len(buf.getvalue()) // 1024, 'KB')
out.append('};')
open(dst, 'w').write('\n'.join(out) + '\n')
